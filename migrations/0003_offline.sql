--     （与 #14「cron_run.task 暂不 CHECK 枚举」同一条纪律）。格式由契约层规定。
--   · **不加 BEFORE UPDATE 触发器** —— 系统里没有「改 client_ref」这条路径，
--     不造没有消费者的约束。
--   · **不新增 synced_at 列** —— created_at 已定义为「服务端接收时刻」，
