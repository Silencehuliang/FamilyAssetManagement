-- 家庭财务管理系统 · D1 schema 迁移 0003：离线记账的幂等键
-- ----------------------------------------------------------------------------
-- 文件：migrations/0003_offline.sql
-- 生成依据：决策票 #10 «PWA 与移动端离线策略»
-- 设计说明：docs/specs/offline-sync-contract.md
-- 可复跑验证：docs/verification/offline-sync-probe.py / .out.txt
--
-- 本迁移只做一件事：给 entry 加一个**由客户端生成**的幂等键 client_ref。
--
--   为什么必须有它：离线队列重放时，「网络超时」与「服务端没写成」是两回事 ——
--   请求可能已经落库、只是响应没回来。没有幂等键，重放就会造出重复的账。
--   在线录入同样有「点保存 → 超时 → 用户再点一次」的同一风险。
--   ⇒ client_ref 是**所有 Entry 都带**的列，不是离线专属。
--
-- 三处结构决定（逐条论证见 offline-sync-contract.md §3）：
--   ① 只能「先加可空列、再建唯一索引」—— SQLite 的 ALTER TABLE ADD COLUMN
--      **不能加 UNIQUE 约束**（#9 已实测踩到；本迁移的探针再次断言，见 §5 C1）。
--   ② 历史行的 client_ref 留 NULL —— SQLite 唯一索引中 **NULL 互不冲突**，
--      这正好是「历史行无需幂等键」的语义。
--      ⚠️ 注意这与 #14 的预算版本 NULL 陷阱是**同一条事实、相反的用法**：
--      那里 NULL 冲突不了是 bug（要靠两条部分唯一索引绕开），
--      这里 NULL 冲突不了正是我们要的（历史行共存）。
--   ③ 新行必须非空 —— 由 BEFORE INSERT 触发器把关。触发器只作用于新写入，
--      不动历史行 ⇒ 这就是「加列 + 索引 + 触发器」三步、而非一条 DDL 的原因。
--
-- 依赖：entry 已存在（0001_init.sql）。
-- ============================================================================


-- ============================================================================
-- 1. 加列（可空）
-- ============================================================================

ALTER TABLE entry ADD COLUMN client_ref TEXT;


-- ============================================================================
-- 2. 唯一索引：幂等重放的写入闸
-- ============================================================================

-- 消费者是**写入闸**（不是 SELECT）：重放的 INSERT 带
--   ON CONFLICT(client_ref) DO NOTHING
-- 靠这个唯一索引判定「这条已经写过了」。与 0001 的 ux_budget_tag_version /
-- ux_budget_household_version 同属「由写入闸消费的唯一索引」那一类。
CREATE UNIQUE INDEX ux_entry_client_ref ON entry(client_ref);


-- ============================================================================
-- 3. 新行必须带 client_ref
-- ============================================================================

-- 为什么不用列上的 CHECK：ALTER TABLE ADD COLUMN 若带 CHECK，该约束会立即
--   对表内**既有行**求值，而历史行根本没有这个值（实测见探针 §5 C3）。
--   触发器天然只作用于新写入，是这里唯一可控的形态。
CREATE TRIGGER trg_entry_client_ref_required
BEFORE INSERT ON entry
WHEN NEW.client_ref IS NULL
BEGIN
  SELECT RAISE(ABORT, 'entry: client_ref 不能为空（新写入必须带客户端幂等键）');
END;


